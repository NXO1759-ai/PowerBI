/* Company Overview renderer — reads window.COMPANY_OVERVIEW_DATA
   (generated by frontend/export_dashboard_data.py from finance_db). */

(function () {
  "use strict";

  var D = window.COMPANY_OVERVIEW_DATA;
  if (!D) {
    document.body.innerHTML =
      '<p style="padding:40px;text-align:center">Data file missing — run ' +
      "<code>python frontend/export_dashboard_data.py</code>.</p>";
    return;
  }

  /* ----------------------------- formatting ----------------------------- */
  var nf0 = new Intl.NumberFormat("en-US", { maximumFractionDigits: 0 });

  function money(v) {
    if (v === null || v === undefined) return null;
    return nf0.format(Math.round(v));
  }

  function pct(v) {
    if (v === null || v === undefined) return null;
    return (v * 100).toFixed(1) + "%";
  }

  function plain(v) {
    if (v === null || v === undefined) return null;
    if (typeof v === "string") return v;
    return nf0.format(Math.round(v));
  }

  function cell(v, fmt) {
    var s = fmt === "pct" ? pct(v) : fmt === "plain" ? plain(v)
      : fmt === "price" ? (v == null ? null : "$" + v.toFixed(4))
      : money(v);
    if (s === null) return '<td class="num mute">—</td>';
    var neg = typeof v === "number" && v < 0 ? " neg" : "";
    return '<td class="num' + neg + '">' + s + "</td>";
  }

  function pctChange(q, c) {
    if (typeof q !== "number" || typeof c !== "number" || c === 0) return null;
    var v = ((q - c) / Math.abs(c)) * 100;
    return (v >= 0 ? "+" : "") + v.toFixed(1) + "%";
  }

  function fillTable(id, rows, labels) {
    var tbl = document.getElementById(id);
    var qLab = (labels && labels[0]) || D.period.label || "Last Qtr";
    var cLab = (labels && labels[1]) || D.period.compareLabel || "Same Qtr LY";
    var tgl = document.getElementById("pct-toggle");
    var pctOn = !!(tgl && tgl.checked);
    tbl.querySelector("thead").innerHTML =
      "<tr><th></th><th>" + qLab + "</th><th>" + cLab + "</th>" +
      (pctOn ? "<th>Δ %</th>" : "") + "</tr>";
    tbl.querySelector("tbody").innerHTML = rows
      .map(function (r) {
        var pc = "";
        if (pctOn) {
          var pv = r[3] === "pct" ? null : pctChange(r[1], r[2]);
          pc = pv === null
            ? '<td class="num mute">—</td>'
            : '<td class="num' + (pv.charAt(0) === "-" ? " neg" : "") +
              '">' + pv + "</td>";
        }
        return (
          "<tr><td>" + r[0] + "</td>" +
          cell(r[1], r[3]) + cell(r[2], r[3]) + pc + "</tr>"
        );
      })
      .join("");
  }

  /* ------------------------------- header ------------------------------- */
  document.getElementById("company-name").textContent = D.company.name;
  document.getElementById("header-sub").textContent =
    "Company Overview · debtsheet-style";

  var filing = D.latestFiling
    ? D.latestFiling.form + " · " + D.latestFiling.date
    : "—";

  var mkt = (D.price && D.price.market) || null;
  var earn = D.earnings || null;

  function usd4(v) {
    if (v === null || v === undefined) return "—";
    return (v < 0 ? "-$" : "$") + Math.abs(v).toFixed(4);
  }
  function signedUsd4(v) {
    if (v === null || v === undefined) return "—";
    return (v < 0 ? "-$" : "+$") + Math.abs(v).toFixed(4);
  }

  var facts = [
    ["Symbol", D.company.ticker, false],
    ["Exchange", D.company.exchange, false],
    ["CIK", String(D.company.cik), false],
    ["Latest Filing", filing, false],
    ["Filing Period", D.period.label || "—", false],
    ["Fiscal Year End", "Dec 31", false],
    ["Website", D.company.website
      ? '<a href="' + D.company.website + '" target="_blank" rel="noopener">' +
        D.company.website.replace(/^https?:\/\//, "").replace(/\/$/, "") + "</a>"
      : "—", !D.company.website],
  ];

  document.getElementById("header-facts").innerHTML = facts
    .map(function (f) {
      return (
        '<div class="fact"><div class="fact-label">' + f[0] +
        '</div><div class="fact-value' + (f[2] ? " pending-value" : "") +
        '">' + f[1] + "</div></div>"
      );
    })
    .join("");

  /* ------------------------- header stats strip --------------------------- */
  function stat(label, valueHtml, cls, sub) {
    return (
      '<div class="stat"><div class="stat-label">' + label +
      '</div><div class="stat-value' + (cls ? " " + cls : "") + '">' +
      valueHtml + "</div>" +
      (sub ? '<div class="stat-sub">' + sub + "</div>" : "") + "</div>"
    );
  }

  var stats = [];
  if (mkt) {
    stats.push(stat("Market Price", usd4(mkt.currentPrice), "",
      "OHLC avg · " + mkt.asOf));
    if (mkt.change2d) {
      var ch = mkt.change2d;
      stats.push(stat("2-Day Change", signedUsd4(ch.abs),
        ch.abs >= 0 ? "stat-up" : "stat-down",
        (ch.abs >= 0 ? "+" : "-") + Math.abs(ch.pct).toFixed(2) +
        "% vs " + ch.vsDate));
    }
  } else {
    stats.push(stat("Market Price", "Pending", "mute", "no price data"));
  }
  if (earn) {
    var ef = earn.epsFiled;
    stats.push(stat("EPS — last filing",
      ef && ef.q !== null ? (ef.q < 0 ? "-$" : "$") + Math.abs(ef.q).toFixed(2) : "—",
      "", D.period.label + " · as reported"));
    var ec = earn.epsComputed;
    stats.push(stat("EPS — computed",
      ec ? usd4(ec.q) : "—", ec && ec.q < 0 ? "stat-down" : "",
      "net income ÷ shares out."));
    stats.push(stat("EPS vs Analyst Est.", "No coverage", "mute",
      "no estimates for KBLB"));
  }

  document.getElementById("header-stats").innerHTML = stats.join("");

  /* --------------------------- fundamentals ----------------------------- */
  var bs = D.fundamentals.balanceSheet;
  var is = D.fundamentals.incomeStatement;
  var cf = D.fundamentals.cashFlow;
  var burn = D.fundamentals.burnRate;

  function renderFundamentals() {
    fillTable("tbl-burn", [
      ["Net Cash Change", burn.q.netCashChange, burn.ly.netCashChange],
      ["Monthly Burn (÷ 3 mo)", burn.q.monthlyBurn, burn.ly.monthlyBurn],
      ["Remaining Cash (Days)",
       burn.q.remainingCashDays, burn.ly.remainingCashDays, "plain"],
    ]);

    fillTable("tbl-bs", [
      ["Cash", bs.cash.q, bs.cash.ly],
      ["Current Assets", bs.currentAssets.q, bs.currentAssets.ly],
      ["Current Liabilities", bs.currentLiabilities.q, bs.currentLiabilities.ly],
      ["Working Capital", bs.workingCapital.q, bs.workingCapital.ly],
      ["Retained Earnings (Deficit)", bs.retainedEarnings.q, bs.retainedEarnings.ly],
      ["Total Assets", bs.totalAssets.q, bs.totalAssets.ly],
      ["Total Liabilities", bs.totalLiabilities.q, bs.totalLiabilities.ly],
      ["Stockholders Equity", bs.equity.q, bs.equity.ly],
    ]);

    fillTable("tbl-is", [
      ["Revenue", is.revenue.q, is.revenue.fy],
      ["COGS", is.cogs.q, is.cogs.fy],
      ["Gross Profit", is.grossProfit.q, is.grossProfit.fy],
      ["Gross Margin %", is.grossMarginPct.q, is.grossMarginPct.fy, "pct"],
      ["Net Income (Loss)", is.netIncome.q, is.netIncome.fy],
    ], [D.period.isLabel, D.period.isCompareLabel]);

    fillTable("tbl-cf", [
      ["CF from Ops", cf.cfOps.q, cf.cfOps.ly],
      ["CF from Inv", cf.cfInv.q, cf.cfInv.ly],
      ["CF from Fin", cf.cfFin.q, cf.cfFin.ly],
      ["Net Cash Change", cf.netCashChange.q, cf.netCashChange.ly],
    ]);
  }

  renderFundamentals();
  var pctBox = document.getElementById("pct-toggle");
  if (pctBox) pctBox.addEventListener("change", renderFundamentals);

  /* --------------------------- share information ------------------------ */
  var sh = D.shares.outstanding;
  var sharesTbl = document.getElementById("tbl-shares");
  sharesTbl.querySelector("thead").innerHTML =
    "<tr><th></th><th>Value</th></tr>";
  sharesTbl.querySelector("tbody").innerHTML = [
    ["Shares Outstanding", sh, "money"],
    ["Current Price (OHLC avg)", mkt ? mkt.currentPrice : null, "price"],
    ["4.99% of Outstanding", mkt ? mkt.shares499 : null, "money"],
    ["Dollar Value of 4.99%", mkt ? mkt.value499 : null, "money"],
    ["Market Capitalization", mkt ? mkt.marketCap : null, "money"],
  ]
    .map(function (r) {
      return "<tr><td>" + r[0] + "</td>" + cell(r[1], r[2]) + "</tr>";
    })
    .join("");

  /* ------------------------- volume statistics -------------------------- */
  if (D.price) {
    var vs = D.price.volumeStats;
    var vl = D.price.valueStats;
    document.getElementById("tbl-vol").querySelector("thead").innerHTML =
      "<tr><th></th><th>Shares</th></tr>";
    document.getElementById("tbl-vol").querySelector("tbody").innerHTML = [
      ["AVG per day — latest 30 trading days", vs.avg30],
      ["AVG per day — latest 60 trading days", vs.avg60],
      ["AVG per day — latest 90 trading days", vs.avg90],
      ["Minimum volume — latest 30 trading days", vs.min30],
      ["Maximum volume — latest 30 trading days", vs.max30],
    ]
      .map(function (r) {
        return "<tr><td>" + r[0] + "</td>" + cell(r[1], "money") + "</tr>";
      })
      .join("");

    document.getElementById("tbl-val").querySelector("thead").innerHTML =
      "<tr><th></th><th>US$</th></tr>";
    document.getElementById("tbl-val").querySelector("tbody").innerHTML = [
      ["AVG per day — latest 30 trading days", vl.avg30, "money"],
      ["AVG per day — latest 60 trading days", vl.avg60, "money"],
      ["AVG per day — latest 90 trading days", vl.avg90, "money"],
      ["Minimum value — latest 30 trading days", vl.min30, "money"],
      ["Maximum value — latest 30 trading days", vl.max30, "money"],
      ["Days traded under $5,000 — last 30 days", vl.daysUnder5k30, "plain"],
    ]
      .map(function (r) {
        return "<tr><td>" + r[0] + "</td>" + cell(r[1], r[2]) + "</tr>";
      })
      .join("");

    function liqCell(x) {
      if (!x) return '<td class="num mute">—</td>';
      return '<td class="num">' + x.days.toFixed(1) + "d / " +
        x.months.toFixed(1) + "mo</td>";
    }
    document.getElementById("liq-tables").innerHTML = D.price.liquidation
      .map(function (block) {
        var rows = block.rows
          .map(function (r) {
            return (
              "<tr><td>$" + nf0.format(r.amount) + "</td>" +
              liqCell(r.d30) + liqCell(r.d60) + liqCell(r.d90) + "</tr>"
            );
          })
          .join("");
        return (
          '<table class="grid liq"><thead><tr><th>' +
          Math.round(block.pct * 100) + "% of volume</th><th>30d</th>" +
          "<th>60d</th><th>90d</th></tr></thead><tbody>" + rows +
          "</tbody></table>"
        );
      })
      .join("");
  }

  /* ------------------------------- charts ------------------------------- */
  function fmtDate(iso) {
    var d = new Date(iso + "T00:00:00");
    return d.toLocaleDateString("en-US", { month: "numeric", day: "numeric" });
  }

  function compactUsd(v) {
    if (v >= 1e6) return "$" + (v / 1e6).toFixed(1) + "M";
    if (v >= 1e3) return "$" + (v / 1e3).toFixed(0) + "k";
    return "$" + v;
  }

  function buildChart(canvasId, rows) {
    var ctx = document.getElementById(canvasId);
    if (!ctx || !window.Chart) return;
    new Chart(ctx, {
      data: {
        labels: rows.map(function (r) { return fmtDate(r.date); }),
        datasets: [
          {
            type: "bar",
            label: "Value Traded (US$)",
            data: rows.map(function (r) { return r.valueTraded; }),
            backgroundColor: "rgba(220, 38, 38, 0.55)",
            borderColor: "rgba(220, 38, 38, 0.9)",
            borderWidth: 1,
            yAxisID: "y1",
            order: 2,
          },
          {
            type: "line",
            label: "OHLC Average",
            data: rows.map(function (r) { return r.ohlcAvg; }),
            borderColor: "rgba(29, 78, 216, 0.95)",
            backgroundColor: "rgba(29, 78, 216, 0.95)",
            borderWidth: 1.5,
            pointRadius: 0,
            tension: 0.25,
            yAxisID: "y",
            order: 1,
          },
        ],
      },
      options: {
        responsive: true,
        maintainAspectRatio: false,
        interaction: { mode: "index", intersect: false },
        plugins: {
          legend: { position: "bottom", labels: { boxWidth: 12, font: { size: 10 } } },
          tooltip: {
            callbacks: {
              label: function (item) {
                return item.dataset.label + ": " +
                  (item.dataset.yAxisID === "y"
                    ? "$" + item.parsed.y.toFixed(4)
                    : compactUsd(item.parsed.y));
              },
            },
          },
        },
        scales: {
          x: { ticks: { maxTicksLimit: 10, font: { size: 9 } }, grid: { display: false } },
          y: {
            position: "left",
            title: { display: true, text: "Price (US$)", font: { size: 9 } },
            ticks: { callback: function (v) { return "$" + v.toFixed(3); }, font: { size: 9 } },
          },
          y1: {
            position: "right",
            title: { display: true, text: "Value Traded", font: { size: 9 } },
            ticks: { callback: compactUsd, font: { size: 9 } },
            grid: { drawOnChartArea: false },
          },
        },
      },
    });
  }

  if (D.price && D.price.series) {
    buildChart("chart-30d", D.price.series30);
    buildChart("chart-6m", D.price.series);
  }

  /* ------------------------- company information -------------------------- */
  (function () {
    var box = document.getElementById("company-info");
    if (!box) return;
    var rows = [];
    if (D.company.website) {
      rows.push(["Website",
        '<a href="' + D.company.website + '" target="_blank" rel="noopener">' +
        D.company.website.replace(/^https?:\/\//, "").replace(/\/$/, "") +
        "</a>"]);
    }
    if (D.company.phone) rows.push(["Phone", D.company.phone]);
    if (D.company.industry) rows.push(["Industry", D.company.industry]);
    if (D.company.ipo_date) rows.push(["IPO Date", D.company.ipo_date]);
    if (D.company.float_shares) {
      rows.push(["Float Shares", nf0.format(D.company.float_shares)]);
    }
    var html = "";
    if (rows.length) {
      html +=
        '<div class="info-block"><h3>Profile</h3><table class="grid"><tbody>' +
        rows.map(function (r) {
          return "<tr><td>" + r[0] + '</td><td class="num">' + r[1] +
            "</td></tr>";
        }).join("") + "</tbody></table></div>";
    }
    html +=
      '<div class="info-block"><h3>Company Description</h3>' +
      '<p class="pending-note">Not available — SEC, Finnhub and Alpha ' +
      "Vantage carry no business description for this OTC ticker.</p></div>" +
      '<div class="info-block"><h3>Management</h3>' +
      '<p class="pending-note">Not available — the officers endpoint is ' +
      "Finnhub premium; SEC and Alpha Vantage have no list for KBLB.</p></div>" +
      '<div class="info-block"><h3>Major Shareholders</h3>' +
      '<p class="pending-note">Not available from SEC / Finnhub / Alpha ' +
      "Vantage for KBLB.</p></div>" +
      '<div class="info-block"><h3>Service Providers</h3>' +
      '<p class="pending-note">Accountant · Attorney · Transfer Agent — ' +
      "pending manual research from filings.</p></div>";
    box.innerHTML = html;
  })();

  /* --------------------------- analyst insight ---------------------------- */
  (function () {
    var box = document.getElementById("analyst-body");
    if (!box || !D.insight) return;
    var ins = D.insight;
    var html = "";

    function srcLink(s) {
      if (!s) return "";
      if (s.form) {
        return '<a href="' + s.url + '" target="_blank" rel="noopener">' +
          s.form + " · " + s.filedDate + "</a>";
      }
      if (s.title) {
        return '<a href="' + s.url + '" target="_blank" rel="noopener">' +
          (s.source || "news") + " · " + String(s.date || "").slice(0, 10) +
          "</a>";
      }
      return "";
    }

    /* 1 — Company Needs */
    var cn = ins.company_needs;
    if (cn) {
      var blocks = [
        ["General Direction", cn.general_direction],
        ["Plans — Coming Years", cn.plans],
        ["Uses of Funds", cn.uses_of_funds],
        ["Sources of Funds", cn.sources_of_funds],
        ["Financing Need", cn.financing_need],
      ];
      html += '<div class="insight-sec"><h3>Company Needs</h3>' +
        blocks.filter(function (b) { return !!b[1]; }).map(function (b) {
          return '<div class="needs-block"><div class="needs-label">' +
            b[0] + "</div><p>" + b[1] + "</p></div>";
        }).join("") + "</div>";
    }

    /* 2 — Financing Activities */
    var fa = ins.financing_activities;
    if (fa && fa.length) {
      html += '<div class="insight-sec"><h3>Financing Activities</h3>' +
        fa.map(function (a) {
          return (
            '<div class="fin-act">' +
            '<div class="fin-act-head"><span class="fin-type">' + a.type +
            "</span>" +
            (a.status
              ? '<span class="fin-status">' + a.status + "</span>"
              : "") +
            "</div>" +
            (a.counterparty
              ? '<div class="fin-counter">Counterparty: ' + a.counterparty +
                "</div>"
              : "") +
            "<p>" + (a.terms || "") + "</p>" +
            (srcLink(a.source)
              ? '<div class="insight-src">Source: ' + srcLink(a.source) +
                "</div>"
              : "") +
            "</div>"
          );
        }).join("") + "</div>";
    }

    /* 3 — News (value-traded spikes + Marketaux headlines) */
    var spikes = ins.spike_analysis || [];
    var news = ins.news || [];
    if (spikes.length || news.length) {
      html += '<div class="insight-sec"><h3>News</h3>';
      if (spikes.length) {
        html += '<div class="news-sub">Value-Traded Spikes</div>' +
          spikes.map(function (s) {
            var links = (s.sources || []).map(srcLink)
              .filter(function (x) { return !!x; });
            var src = links.length
              ? '<div class="insight-src">Sources: ' + links.join(" · ") +
                "</div>"
              : '<div class="insight-src mute">No filing or news source ' +
                "available for this date.</div>";
            return (
              '<div class="spike"><div class="spike-date">' + s.date +
              "</div><p>" + s.observation + "</p><ul>" +
              (s.drivers || []).map(function (d) {
                return "<li>" + d + "</li>";
              }).join("") + "</ul>" + src + "</div>"
            );
          }).join("");
      }
      if (news.length) {
        html += '<div class="news-sub">Headlines · Marketaux</div>' +
          news.map(function (n) {
            return (
              '<div class="news-item"><div class="news-date">' +
              String(n.date || "").slice(0, 10) + " · " + (n.source || "") +
              '</div><a href="' + n.url + '" target="_blank" rel="noopener">' +
              n.title + "</a>" +
              (n.relevance ? "<p>" + n.relevance + "</p>" : "") + "</div>"
            );
          }).join("");
      }
      html += "</div>";
    }

    if (ins.caveats) {
      html += '<div class="insight-caveats">' + ins.caveats + "</div>";
    }
    html +=
      '<div class="insight-caveats">AI analysis (DeepSeek) built from ' +
      "finance_db facts, SEC filing text and Marketaux news · generated " +
      D.generatedAt.slice(0, 10) + ".</div>";
    box.innerHTML = html;
  })();

  /* ------------------------------- footer ------------------------------- */
  document.getElementById("footer").textContent =
    "Source: " + D.source + " · generated " + D.generatedAt;
})();
