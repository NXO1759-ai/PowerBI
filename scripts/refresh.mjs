/**
 * refresh.mjs — the weekly refresh.
 *
 *   node scripts/refresh.mjs [--limit N] [--ticker AAPL] [--out DIR]
 *
 * Pulls fundamentals for the covered universe straight from SEC EDGAR,
 * validates every payload against frontend/lib/metrics.js, rewrites
 * frontend/data/company-*.js, and emits two artifacts:
 *
 *   frontend/data/quality-report.json  what was checked and what failed
 *   sql/sync/facts-<date>.sql          the same figures as MySQL upserts
 *
 * The SQL file is the bridge. The website reads the data files, Power BI
 * reads the MySQL views, and both are generated from one pull in one run,
 * so the three surfaces cannot drift apart. Applying the SQL brings the
 * local database — and therefore Power BI — to exactly what the site is
 * serving.
 *
 * Zero dependencies and no database connection, so this runs unchanged in
 * GitHub Actions where the local MySQL is unreachable.
 *
 * Exit codes: 0 clean, 1 error-severity findings, 2 the pull itself failed.
 */

import { createRequire } from "node:module";
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
/* the browser's own metrics file, loaded as a module — one definition */
const M = require(join(ROOT, "frontend/lib/metrics.js"));
const { pullCompany, SEC_CONCEPTS } = await import("./lib/sec-pull.mjs");

/* ---------- arguments ---------- */
const argv = process.argv.slice(2);
const arg = (name, fallback = null) => {
  const i = argv.indexOf(`--${name}`);
  return i !== -1 && argv[i + 1] ? argv[i + 1] : fallback;
};
const LIMIT = Number(arg("limit", "0")) || 0;
const ONLY = (arg("ticker", "") || "").toUpperCase();
const OUT_DIR = resolve(arg("out", join(ROOT, "frontend/data")));
const SQL_DIR = join(ROOT, "sql/sync");

/* ---------- universe ---------- */
/* company-index.js and coverage.js are plain assignments to window.*, so
   they are read by evaluating them against a stub rather than parsed. */
function loadUniverse() {
  const stub = {};
  const evalInto = (file) => {
    const src = readFileSync(join(ROOT, "frontend/data", file), "utf8");
    new Function("window", src)(stub);
  };
  evalInto("company-index.js");
  evalInto("coverage.js");
  const index = Array.isArray(stub.COMPANY_INDEX) ? stub.COMPANY_INDEX : [];
  const covered = new Set(
    Array.isArray(stub.COMPANY_COVERAGE) ? stub.COMPANY_COVERAGE : []);
  const byTicker = new Map(index.map((r) => [r[0], { ticker: r[0], cik: r[1], name: r[2] }]));
  let list = [...covered].map((t) => byTicker.get(t)).filter(Boolean);
  if (ONLY) list = list.filter((c) => c.ticker === ONLY);
  if (LIMIT) list = list.slice(0, LIMIT);
  return list;
}

/* ---------- emit ---------- */
function writeDataFile(company, payload) {
  const file = join(OUT_DIR, `company-${company.ticker.toLowerCase()}.js`);
  const body =
    "// Generated by scripts/refresh.mjs — do not edit.\n" +
    "window.COMPANY_OVERVIEW_DATA = " +
    JSON.stringify(payload, null, 2) + ";\n";
  writeFileSync(file, body, "utf8");
}

const sqlStr = (v) =>
  v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`;
const sqlNum = (v) => (M.isNum(v) ? String(v) : "NULL");

/* Upserts, not inserts: re-running a week later must correct a restated
   figure in place rather than stacking a second copy of the same period,
   which is what v_dq_duplicate_facts exists to catch. */
function sqlForCompany(company, payload) {
  const p = payload.period || {};
  if (!p.fiscalYear || !p.fiscalPeriod) return "";
  const f = payload.fundamentals || {};
  const bs = f.balanceSheet || {}, is = f.incomeStatement || {}, cf = f.cashFlow || {};
  const lf = payload.latestFiling || {};
  const rows = [
    ["CashAndCashEquivalentsAtCarryingValue", bs.cash?.q],
    ["AssetsCurrent", bs.currentAssets?.q],
    ["LiabilitiesCurrent", bs.currentLiabilities?.q],
    ["Assets", bs.totalAssets?.q],
    ["Liabilities", bs.totalLiabilities?.q],
    ["StockholdersEquity", bs.equity?.q],
    ["MinorityInterest", bs.minorityInterest?.q],
    ["StockholdersEquityIncludingPortionAttributableToNoncontrollingInterest",
      bs.equityIncludingNci?.q],
    ["RetainedEarningsAccumulatedDeficit", bs.retainedEarnings?.q],
    ["NetIncomeLoss", is.netIncome?.q],
    ["NetCashProvidedByUsedInOperatingActivities", cf.cfOps?.q],
    ["NetCashProvidedByUsedInInvestingActivities", cf.cfInv?.q],
    ["NetCashProvidedByUsedInFinancingActivities", cf.cfFin?.q],
  ].filter(([, v]) => M.isNum(v));
  if (!rows.length) return "";
  const values = rows.map(([concept, value]) =>
    `(${Number(company.cik)}, ${sqlStr(concept)}, 'USD', ${p.fiscalYear}, ` +
    `${sqlStr(p.fiscalPeriod)}, ${sqlStr(payload.periodEnd || null)}, ` +
    `${sqlNum(value)}, ${sqlStr(lf.date || null)}, ${sqlStr(lf.form || null)})`
  ).join(",\n  ");
  return (
    `-- ${company.ticker} (CIK ${company.cik}) ${p.label}\n` +
    "INSERT INTO financial_facts\n" +
    "  (cik, concept, unit, fiscal_year, fiscal_period, period_end, value, filed_date, form)\n" +
    "VALUES\n  " + values + "\n" +
    "ON DUPLICATE KEY UPDATE\n" +
    "  value = VALUES(value), period_end = VALUES(period_end),\n" +
    "  filed_date = VALUES(filed_date), form = VALUES(form);\n"
  );
}

/* ---------- run ---------- */
const started = new Date();
const universe = loadUniverse();
if (!universe.length) {
  console.error("refresh: universe is empty — check frontend/data/coverage.js");
  process.exit(2);
}
console.log(`refresh: ${universe.length} companies, ${SEC_CONCEPTS.length} concepts each`);
mkdirSync(OUT_DIR, { recursive: true });

const report = {
  startedAt: started.toISOString(),
  definitionsVersion: M.DEFINITIONS_VERSION,
  companiesAttempted: universe.length,
  companiesWritten: 0,
  companiesFailed: [],
  findings: [],
  errorCount: 0,
  warnCount: 0,
};
const sqlChunks = [];

for (const company of universe) {
  let payload = null;
  try {
    payload = await pullCompany(company);
  } catch (e) {
    report.companiesFailed.push({ ticker: company.ticker, reason: String(e && e.message || e) });
    continue;
  }
  if (!payload) {
    report.companiesFailed.push({ ticker: company.ticker, reason: "no XBRL facts returned" });
    continue;
  }

  const findings = M.validateCompany(payload);
  for (const f of findings) {
    report.findings.push({ ticker: company.ticker, ...f });
    if (f.severity === "error") report.errorCount++;
    else report.warnCount++;
  }
  /* An error-severity payload is internally inconsistent, so publishing it
     would put a wrong number on the site. Keep the previous file. */
  if (findings.some((f) => f.severity === "error")) {
    report.companiesFailed.push({
      ticker: company.ticker,
      reason: "validation errors: " +
        findings.filter((f) => f.severity === "error").map((f) => f.code).join(", "),
    });
    continue;
  }

  writeDataFile(company, payload);
  report.companiesWritten++;
  const chunk = sqlForCompany(company, payload);
  if (chunk) sqlChunks.push(chunk);
  process.stdout.write(".");
}
process.stdout.write("\n");

report.finishedAt = new Date().toISOString();
report.durationSeconds = Math.round((Date.now() - started.getTime()) / 1000);

writeFileSync(join(OUT_DIR, "quality-report.json"),
  JSON.stringify(report, null, 2) + "\n", "utf8");

if (sqlChunks.length) {
  mkdirSync(SQL_DIR, { recursive: true });
  const stamp = started.toISOString().slice(0, 10);
  const header =
    `-- Generated by scripts/refresh.mjs on ${started.toISOString()}\n` +
    `-- ${report.companiesWritten} companies, definitions v${M.DEFINITIONS_VERSION}.\n` +
    "-- Apply to bring finance_db (and Power BI) in step with the website:\n" +
    `--   mysql -u learn -p finance_db < sql/sync/facts-${stamp}.sql\n\n`;
  writeFileSync(join(SQL_DIR, `facts-${stamp}.sql`),
    header + sqlChunks.join("\n"), "utf8");
  console.log(`refresh: wrote sql/sync/facts-${stamp}.sql`);
}

console.log(
  `refresh: ${report.companiesWritten} written, ` +
  `${report.companiesFailed.length} skipped, ` +
  `${report.errorCount} errors, ${report.warnCount} warnings, ` +
  `${report.durationSeconds}s`);

for (const f of report.companiesFailed.slice(0, 20)) {
  console.log(`  skipped ${f.ticker}: ${f.reason}`);
}
process.exit(report.errorCount > 0 ? 1 : 0);
