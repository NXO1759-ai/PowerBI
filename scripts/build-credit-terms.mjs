/**
 * build-credit-terms.mjs — the credit glossary as a browser file.
 *
 *   node scripts/build-credit-terms.mjs [out-path]
 *
 * Reads frontend/data/pc/glossary.json and writes frontend/lib/credit-terms.js:
 * an IIFE that assigns window.RTTerms with the term list embedded, the
 * matcher that wraps the first occurrence of each term in every section of
 * a page, and the hover popup. The site has no build step, so the output is
 * committed; the generator is deterministic (terms sorted, fixed key order,
 * the date taken from the JSON, never from the clock) so re-running it on
 * an unchanged glossary yields no diff, and scripts/test-credit-terms.mjs
 * proves that.
 *
 * Only what the hover popup needs is embedded: term, expansion, kind, side,
 * popup, source and aliases, one entry per line. definition stays in the
 * JSON, which the Glossary view fetches the first time it is shown, so a
 * visit that never opens the glossary never downloads it; whereUsed,
 * fixNote and workingRef stay there too as maintenance notes. An empty
 * expansion and an empty alias list are left out of the entry.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "frontend/data/pc/glossary.json");
const OUT = process.argv[2] ? resolve(process.argv[2]) : join(ROOT, "frontend/lib/credit-terms.js");

const KINDS = ["series-id", "acronym", "instrument", "metric", "market", "regulation"];
const SIDES = ["market", "lender", "both"];
const POPUP_MAX = 240;

/* The same checks the test runs, so a bad glossary fails here first. */
export function validate(terms) {
  const problems = [];
  const seen = new Map();
  for (const t of terms) {
    for (const f of ["term", "popup", "definition", "source", "kind", "side"]) {
      if (typeof t[f] !== "string" || !t[f].trim()) problems.push(`${t.term || "?"}: missing ${f}`);
    }
    if (t.popup && t.popup.length > POPUP_MAX) problems.push(`${t.term}: popup is ${t.popup.length} characters`);
    if (!KINDS.includes(t.kind)) problems.push(`${t.term}: kind '${t.kind}'`);
    if (!SIDES.includes(t.side)) problems.push(`${t.term}: side '${t.side}'`);
    for (const k of [t.term, ...(t.aliases || [])]) {
      const key = String(k).toLowerCase();
      if (seen.has(key) && seen.get(key) !== t.term) problems.push(`'${k}' appears on '${t.term}' and '${seen.get(key)}'`);
      seen.set(key, t.term);
    }
  }
  return problems;
}

/* Sorted by term, case-insensitively first so the glossary page reads
   alphabetically, then case-sensitively so the order is total. */
export function sortTerms(terms) {
  const cmp = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
  return terms.slice().sort((a, b) =>
    cmp(a.term.toLowerCase(), b.term.toLowerCase()) || cmp(a.term, b.term));
}

export function build(glossary) {
  const problems = validate(glossary.terms);
  if (problems.length) throw new Error("glossary.json:\n  " + problems.join("\n  "));
  const terms = sortTerms(glossary.terms).map((t) => {
    const o = { term: t.term };
    if (t.expansion) o.expansion = t.expansion;
    o.kind = t.kind; o.side = t.side; o.popup = t.popup; o.source = t.source;
    if (t.aliases && t.aliases.length) o.aliases = t.aliases.slice();
    return o;
  });
  const header =
    "/* credit-terms.js — generated by scripts/build-credit-terms.mjs from\n" +
    "   frontend/data/pc/glossary.json. Do not edit; edit the JSON and re-run.\n" +
    `   ${terms.length} terms, glossary dated ${glossary.generated}. */\n`;
  /* function replacers: a string replacement would expand "$&", "$'" and
     the like inside a popup, and the byte-identical test could not tell */
  const version = JSON.stringify(String(glossary.generated));
  /* one entry per line: compact, and an edit to one term is a one-line diff */
  const json = "[\n" + terms.map((t) => JSON.stringify(t)).join(",\n") + "\n]";
  return header + RUNTIME
    .replace("__VERSION__", function () { return version; })
    .replace("__TERMS__", function () { return json; });
}

/* The browser runtime. Plain ES5 in the UMD shape of lib/http.js so the CI
   parse loop and the test's require() both load it. No backticks or ${ in
   here: it is spliced into a template above. */
const RUNTIME = String.raw`(function (root, factory) {
  if (typeof module === "object" && module.exports) module.exports = factory();
  else root.RTTerms = factory();
})(typeof self !== "undefined" ? self : this, function () {
  "use strict";

  var VERSION = __VERSION__;
  var TERMS = __TERMS__;

  /* ---------- lookup ---------- */

  /* Lower-cased term and alias -> entry. Two entries never share a key:
     the generator refuses a glossary where they do. */
  var INDEX = {};
  TERMS.forEach(function (t) {
    INDEX[t.term.toLowerCase()] = t;
    (t.aliases || []).forEach(function (a) { INDEX[a.toLowerCase()] = t; });
  });
  var index = {
    get: function (key) { return INDEX[String(key).toLowerCase()] || null; },
    has: function (key) { return Object.prototype.hasOwnProperty.call(INDEX, String(key).toLowerCase()); },
    keys: function () { return Object.keys(INDEX); },
    size: Object.keys(INDEX).length
  };
  function lookup(text) { return index.get(text); }

  /* ---------- the matcher ---------- */

  /* Acronyms and series ids match exactly ("NII", not "nii"; "SOFR", not
     "sofr"); so does any string with no lower-case letter, whatever its
     kind (an alias such as "DDTL" on an instrument). Phrases match in any
     case, so "Dividend coverage" at the start of a sentence still resolves. */
  function isSensitive(entry, s) {
    return entry.kind === "acronym" || entry.kind === "series-id" || !/[a-z]/.test(s);
  }
  function escapeRe(s) { return s.replace(/[.*+?^$\{\}()|[\]\\\/]/g, "\\$&"); }
  function anyCase(s) {
    return s.split("").map(function (ch) {
      var lo = ch.toLowerCase(), up = ch.toUpperCase();
      return lo !== up ? "[" + lo + up + "]" : escapeRe(ch);
    }).join("");
  }
  /* Every term and alias, longest first so "core NII" wins over "NII" at
     the same position; ties broken by text so the pattern is stable. */
  var KEYS = [];
  TERMS.forEach(function (t) {
    [t.term].concat(t.aliases || []).forEach(function (s) {
      KEYS.push({ text: s, sensitive: isSensitive(t, s) });
    });
  });
  KEYS.sort(function (a, b) {
    return b.text.length - a.text.length || (a.text < b.text ? -1 : a.text > b.text ? 1 : 0);
  });
  /* Whole words only: the character before is not alphanumeric (or there is
     none) and the character after is not alphanumeric. "$2,899B" does not
     contain the rating "B"; "BB / B / CCC" contains all three. */
  var PATTERN = new RegExp(
    "(^|[^A-Za-z0-9_])(" +
    KEYS.map(function (k) { return k.sensitive ? escapeRe(k.text) : anyCase(k.text); }).join("|") +
    ")(?![A-Za-z0-9_])", "g");

  /* Split a text into plain and matched segments. The first occurrence of
     each entry in a section is a match; later ones are plain, so 'seen'
     (entry term -> true) is shared by every text node of one section and
     mutated here. Pure apart from that: no DOM, so the test can run it. */
  function tokenize(text, seen) {
    var out = [], last = 0, m;
    PATTERN.lastIndex = 0;
    while ((m = PATTERN.exec(text))) {
      var matched = m[2], start = m.index + m[1].length;
      var entry = INDEX[matched.toLowerCase()];
      if (!entry || seen[entry.term]) continue;
      seen[entry.term] = true;
      if (start > last) out.push({ text: text.slice(last, start) });
      out.push({ text: matched, term: entry.term });
      last = start + matched.length;
    }
    if (!out.length) return null;
    if (last < text.length) out.push({ text: text.slice(last) });
    return out;
  }

  /* ---------- wrapping a page ---------- */

  var SKIP_TAGS = { CODE: 1, PRE: 1, SVG: 1, A: 1, BUTTON: 1, INPUT: 1, TEXTAREA: 1, SELECT: 1, SCRIPT: 1, STYLE: 1 };
  function skipped(el) {
    var tag = String(el.tagName || "").toUpperCase();
    if (SKIP_TAGS[tag]) return true;
    if (el.classList && (el.classList.contains("term") || el.classList.contains("metric-pop"))) return true;
    if (el.hasAttribute && (el.hasAttribute("data-no-terms") || el.hasAttribute("data-metric"))) return true;
    return false;
  }
  function matchesSel(el, sel) {
    if (el.matches) return el.matches(sel);
    return String(el.tagName || "").toLowerCase() === sel;
  }

  /* Wrap the first occurrence of each term inside every section of rootEl
     in <span class="term" tabindex="0" data-term="...">. Code, links,
     controls, SVG, the popup, anything under [data-no-terms] and the
     metric labels ([data-metric], which carry their own popup) are left
     alone, as is text already wrapped. Returns the number of spans made.
     opts.perSection is the section selector (default "section"); when
     rootEl contains none it is treated as one section. opts.document lets a
     test supply a document; the page never needs to. */
  function wrap(rootEl, opts) {
    opts = opts || {};
    var doc = opts.document || (typeof document !== "undefined" ? document : null);
    if (!rootEl || !doc) return 0;
    var sel = opts.perSection || "section";
    var sections = rootEl.querySelectorAll ? Array.prototype.slice.call(rootEl.querySelectorAll(sel)) : [];
    if (!sections.length) sections = [rootEl];
    var made = 0;
    sections.forEach(function (sec) {
      var seen = {};
      /* A second call must not wrap the second occurrence: what is already
         wrapped in this section counts as seen. */
      Array.prototype.forEach.call(sec.querySelectorAll("[data-term]"), function (el) {
        var e = INDEX[String(el.getAttribute("data-term")).toLowerCase()];
        if (e) seen[e.term] = true;
      });
      var walker = doc.createTreeWalker(sec, 4 /* NodeFilter.SHOW_TEXT */, {
        acceptNode: function (n) {
          var p = n.parentNode;
          while (p && p !== sec) {
            if (skipped(p)) return 2; /* FILTER_REJECT */
            if (p !== rootEl && matchesSel(p, sel)) return 2; /* a nested section walks itself */
            p = p.parentNode;
          }
          return 1; /* FILTER_ACCEPT */
        }
      });
      var nodes = [];
      while (walker.nextNode()) nodes.push(walker.currentNode);
      nodes.forEach(function (n) {
        var parts = tokenize(n.nodeValue, seen);
        if (!parts) return;
        var frag = doc.createDocumentFragment();
        parts.forEach(function (p) {
          if (!p.term) { frag.appendChild(doc.createTextNode(p.text)); return; }
          var span = doc.createElement("span");
          span.className = "term";
          span.tabIndex = 0;
          span.setAttribute("data-term", p.term);
          span.textContent = p.text;
          frag.appendChild(span);
          made++;
        });
        n.parentNode.replaceChild(frag, n);
      });
    });
    return made;
  }

  /* ---------- the popup ---------- */

  function esc(s) {
    return String(s).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
    });
  }
  /* Two parts and a source: the expansion beside the term, the popup text,
     then where it comes from. Pure, so the test can check the escaping. */
  function html(entry) {
    return "<h4>" + esc(entry.term) +
      (entry.expansion ? " <span class='pop-expansion'>" + esc(entry.expansion) + "</span>" : "") + "</h4>" +
      "<p>" + esc(entry.popup) + "</p>" +
      "<p class='pop-src'><span class='pop-tag'>Source</span>" + esc(entry.source) + "</p>";
  }

  var attached = false;
  /* Show the popup for a .term on hover and focus, hide it on leave, blur
     and Escape. popEl is the page's shared #metric-pop when it has one
     (the metric popups keep using it for [data-metric]; the two never
     overlap because a term is never wrapped inside a metric label), else
     a #term-tip is created. Calling attach twice is a no-op. */
  function attach(popEl) {
    if (attached || typeof document === "undefined") return;
    attached = true;
    var pop = popEl || document.getElementById("metric-pop");
    if (!pop) {
      pop = document.createElement("div");
      pop.id = "term-tip";
      pop.className = "metric-pop";
      pop.setAttribute("role", "tooltip");
      pop.hidden = true;
      document.body.appendChild(pop);
    }
    var popFor = null;
    function show(el) {
      var entry = INDEX[String(el.getAttribute("data-term") || "").toLowerCase()];
      if (!entry) return;
      popFor = el;
      pop.innerHTML = html(entry);
      pop.hidden = false;
      /* Below this width the popup is a bottom sheet positioned by CSS, as
         on the strategy page; inline offsets would strand it off-screen. */
      if (window.matchMedia && window.matchMedia("(max-width: 680px)").matches) {
        pop.style.left = ""; pop.style.top = ""; return;
      }
      var r = el.getBoundingClientRect(), pw = pop.offsetWidth, ph = pop.offsetHeight;
      var left = Math.min(r.left + window.scrollX,
        window.scrollX + document.documentElement.clientWidth - pw - 12);
      var top = r.bottom + window.scrollY + 8;
      if (r.bottom + ph + 20 > document.documentElement.clientHeight) {
        top = Math.max(window.scrollY + 8, r.top + window.scrollY - ph - 8);
      }
      pop.style.left = Math.max(window.scrollX + 8, left) + "px";
      pop.style.top = top + "px";
    }
    /* Only hide what this module showed: a metric popup in the same
       element is someone else's, and stays. */
    function hide(el) {
      if (!popFor) return;
      if (el && popFor !== el) return;
      pop.hidden = true;
      popFor = null;
    }
    function termOf(e) { return e.target && e.target.closest ? e.target.closest(".term[data-term]") : null; }
    document.addEventListener("mouseover", function (e) { var t = termOf(e); if (t) show(t); });
    document.addEventListener("mouseout", function (e) { var t = termOf(e); if (t) hide(t); });
    document.addEventListener("focusin", function (e) { var t = termOf(e); if (t) show(t); });
    document.addEventListener("focusout", function (e) { var t = termOf(e); if (t) hide(t); });
    document.addEventListener("keydown", function (e) { if (e.key === "Escape") hide(); });
  }

  return {
    VERSION: VERSION, TERMS: TERMS, index: index, lookup: lookup,
    tokenize: tokenize, wrap: wrap, attach: attach, html: html,
    pattern: PATTERN.source
  };
});
`;

/* Run as a script: write the file. Imported by the test: only the
   functions above are used. */
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const glossary = JSON.parse(readFileSync(SRC, "utf8"));
  const js = build(glossary);
  writeFileSync(OUT, js, "utf8");
  console.log(`wrote ${OUT} — ${glossary.terms.length} terms, ${Buffer.byteLength(js)} bytes`);
}
